CREATE POLICY "Published universes and origin labels" ON public.universes
    AS PERMISSIVE FOR SELECT TO anon, authenticated
    USING ((is_published OR (EXISTS ( SELECT 1
   FROM characters c
  WHERE (c.origin_universe_id = universes.id)))));

