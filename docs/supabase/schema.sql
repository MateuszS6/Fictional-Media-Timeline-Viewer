CREATE TABLE public.franchises (
    id bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
    name text NOT NULL,
    CONSTRAINT franchises_name_key UNIQUE (name),
    CONSTRAINT franchises_pkey PRIMARY KEY (id)
);

CREATE TABLE public.universes (
    id bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
    franchise_id bigint NOT NULL,
    name text NOT NULL,
    code text,
    is_published boolean DEFAULT false NOT NULL,
    CONSTRAINT universes_franchise_id_fkey FOREIGN KEY (franchise_id) REFERENCES public.franchises(id),
    CONSTRAINT universes_franchise_id_name_key UNIQUE (franchise_id, name),
    CONSTRAINT universes_pkey PRIMARY KEY (id)
);

CREATE TABLE public.projects (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title text NOT NULL,
    release_date date,
    primary_universe_id bigint NOT NULL,
    CONSTRAINT projects_pkey PRIMARY KEY (id),
    CONSTRAINT projects_primary_universe_id_fkey FOREIGN KEY (primary_universe_id) REFERENCES public.universes(id) ON DELETE RESTRICT,
    CONSTRAINT projects_title_key UNIQUE (title)
);

CREATE TABLE public.universe_projects (
    universe_id bigint NOT NULL,
    project_id bigint NOT NULL,
    timeline_position integer NOT NULL,
    CONSTRAINT timeline_projects_position_check CHECK (timeline_position > 0),
    CONSTRAINT timeline_projects_project_id_fkey FOREIGN KEY (project_id) REFERENCES public.projects(id) ON DELETE CASCADE,
    CONSTRAINT universe_projects_pkey PRIMARY KEY (universe_id, project_id),
    CONSTRAINT universe_projects_position_key UNIQUE (universe_id, timeline_position) DEFERRABLE,
    CONSTRAINT universe_projects_universe_id_fkey FOREIGN KEY (universe_id) REFERENCES public.universes(id) ON DELETE RESTRICT
);

CREATE TABLE public.characters (
    id bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
    alias text NOT NULL,
    origin_universe_id bigint NOT NULL,
    real_name text,
    CONSTRAINT characters_origin_universe_id_fkey FOREIGN KEY (origin_universe_id) REFERENCES public.universes(id) ON DELETE RESTRICT,
    CONSTRAINT characters_pkey PRIMARY KEY (id)
);

CREATE TABLE public.appearances (
    character_id bigint NOT NULL,
    project_id bigint NOT NULL,
    appearance_type text DEFAULT 'standard'::text NOT NULL,
    is_detached boolean DEFAULT false NOT NULL,
    universe_id bigint NOT NULL,
    CONSTRAINT appearances_appearance_type_check CHECK ((appearance_type = ANY (ARRAY['standard'::text, 'flashback'::text, 'footage'::text, 'afterlife'::text, 'depiction'::text, 'vision'::text, 'non_chronological'::text]))),
    CONSTRAINT appearances_character_id_fkey FOREIGN KEY (character_id) REFERENCES public.characters(id) ON DELETE CASCADE,
    CONSTRAINT appearances_pkey PRIMARY KEY (universe_id, character_id, project_id),
    CONSTRAINT appearances_project_id_fkey FOREIGN KEY (project_id) REFERENCES public.projects(id) ON DELETE CASCADE,
    CONSTRAINT appearances_universe_project_fkey FOREIGN KEY (universe_id, project_id) REFERENCES public.universe_projects(universe_id, project_id) ON DELETE CASCADE
);

CREATE TABLE public.character_events (
    id bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
    character_id bigint NOT NULL,
    project_id bigint NOT NULL,
    event_type text NOT NULL,
    event_position text DEFAULT 'at'::text NOT NULL,
    universe_id bigint NOT NULL,
    CONSTRAINT character_events_character_id_fkey FOREIGN KEY (character_id) REFERENCES public.characters(id) ON DELETE CASCADE,
    CONSTRAINT character_events_event_position_check CHECK (event_position = ANY (ARRAY['at'::text, 'after'::text])),
    CONSTRAINT character_events_event_type_check CHECK ((event_type = ANY (ARRAY['death'::text, 'revival'::text, 'blip'::text, 'return'::text, 'unknown'::text]))),
    CONSTRAINT character_events_pkey PRIMARY KEY (id),
    CONSTRAINT character_events_project_id_fkey FOREIGN KEY (project_id) REFERENCES public.projects(id) ON DELETE CASCADE,
    CONSTRAINT character_events_universe_character_project_key UNIQUE (universe_id, character_id, project_id),
    CONSTRAINT character_events_universe_project_fkey FOREIGN KEY (universe_id, project_id) REFERENCES public.universe_projects(universe_id, project_id) ON DELETE CASCADE
);

